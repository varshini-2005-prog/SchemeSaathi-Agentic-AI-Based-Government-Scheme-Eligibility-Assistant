"""
app/agents/response_generator.py
Final Response Formatting Agent for SchemeSaathi.
Formats eligibility decisions, rule explanations, source citations, and required documents.
Supports natural language responses in English, Tamil, and Tanglish.
"""

from typing import Dict, Any, List
from app.graph.state import SchemeState
from app.utils.logger import logger


class ResponseGeneratorAgent:
    """Formats final user output following strict project specification format."""

    def format_final_response(self, state: SchemeState) -> SchemeState:
        """
        Node function that compiles eligibility results into clean markdown output.
        """
        if state.get("is_what_if") and state.get("final_response"):
            # Response already generated by what-if simulator
            return state

        eligibility_results = state.get("eligibility_results", [])
        verification_results = state.get("verification_results", [])
        required_docs = state.get("required_documents", [])
        next_steps = state.get("next_steps", [])
        missing_fields = state.get("missing_fields", [])
        lang = state.get("language", "en")

        lines = []

        # Header disclaimer
        lines.append("⚠️ **Disclaimer:** *SchemeSaathi provides informational guidance only. Always verify latest official eligibility criteria with official government sources before applying.*\n")

        # 1. Active Scheme Cards
        for res in eligibility_results:
            scheme_name = res["scheme_name"]
            status = res["overall_status"]
            benefits = res["benefits"]
            source_doc = res["source_document"]
            url = res["official_url"]

            # Find matching verification result
            verif = next((v for v in verification_results if v["scheme_id"] == res["scheme_id"]), {})
            verif_status = verif.get("verification_status", "VERIFIED")

            status_badge = "✅ Eligible" if status == "ELIGIBLE" else ("❌ Not Eligible" if status == "NOT ELIGIBLE" else "⚠️ Need More Information")

            lines.append(f"### 🏛️ {scheme_name}")
            lines.append(f"**Status:** {status_badge}\n")

            lines.append("**Why:**")
            for r in res.get("rule_evaluations", []):
                r_status = r["status"]
                badge = "PASS" if r_status == "PASS" else ("FAIL" if r_status == "FAIL" else "UNKNOWN")
                lines.append(f"• {r['description']}: `{badge}` (User value: `{r['user_value']}` | Required: `{r['operator']} {r['target_value']}`)")

            lines.append(f"\n**Benefits:** {benefits}")

            if status in ["ELIGIBLE", "NEED MORE INFORMATION"]:
                lines.append("\n**Required Documents:**")
                for doc in res.get("required_documents", []):
                    lines.append(f"• {doc}")

            lines.append(f"\n**Official Source:** [{source_doc}]({url})")
            lines.append(f"**Verification:** ✓ `{verif_status}` against official source document.\n")
            lines.append("---")

        # 2. Missing fields prompt if any
        if missing_fields:
            lines.append("\n❓ **To get a confirmed eligibility decision, please answer:**")
            question_map = {
                "age": "What is your age?",
                "annual_family_income": "What is your annual family income?",
                "occupation": "What is your occupation (Student / Farmer)?",
                "education_status": "Are you pursuing higher education (Degree/Diploma/ITI)?",
                "govt_school_study_class_6_to_12": "Did you study Class 6 to 12 in a Tamil Nadu Government School?",
                "land_ownership": "Do you own agricultural land?",
                "four_wheeler_ownership": "Do you own a four-wheeler car/jeep?",
                "annual_electricity_units": "Is annual electricity consumption under 3,600 units?",
            }
            for field in missing_fields:
                q = question_map.get(field, f"What is your {field}?")
                lines.append(f"• {q}")

        state["final_response"] = "\n".join(lines)
        logger.info("Response Generator compiled final markdown response.")
        return state


response_generator = ResponseGeneratorAgent()
